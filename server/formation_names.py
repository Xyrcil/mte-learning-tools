"""Runtime-compatible formation names and legacy-default migration.

Static CIL analysis of ``TeamView.NameValueChange`` proves that the runtime
limits a formation name to a weighted length of eight: characters in
U+4E00..U+9FA5 count as two and every other UTF-16 code unit counts as one.
``TeamView.SendChangeName`` also rejects empty names and names containing the
filter replacement marker ``*``.

Early versions of the local server generated ``Local Team`` and
``Test Team N``.  Those names have weighted lengths of ten and eleven, so the
runtime cannot round-trip them through its editor.  Only those known generated
values are migrated; all other non-empty saved names remain user-owned.
"""

from __future__ import annotations

from typing import Any


CLIENT_FORMATION_NAME_WEIGHT_LIMIT = 8
FILTER_REPLACEMENT_MARKER = "*"

LEGACY_GENERATED_FORMATION_NAMES = frozenset(
    {"Local Team", *(f"Test Team {slot + 1}" for slot in range(5))}
)


def default_formation_name(slot: int) -> str:
    """Return the short, runtime-compatible name for a zero-based slot."""

    slot = int(slot)
    if slot < 0:
        raise ValueError("formation slot cannot be negative")
    return f"队伍{slot + 1}"


def formation_name_weight(value: str) -> int:
    """Mirror ``StringExtend.GetStringLen`` from runtime assembly.

    C# iterates UTF-16 ``char`` values.  Supplementary Unicode characters are
    therefore two non-Chinese code units, while U+4E00..U+9FA5 each count as
    two explicitly.
    """

    if not isinstance(value, str):
        raise TypeError("formation name must be a string")
    weight = 0
    for character in value:
        codepoint = ord(character)
        if 0x4E00 <= codepoint <= 0x9FA5:
            weight += 2
        else:
            weight += len(character.encode("utf-16-le", errors="surrogatepass")) // 2
    return weight


def is_client_valid_formation_name(value: Any) -> bool:
    """Return whether the runtime can submit ``value`` unchanged."""

    return (
        isinstance(value, str)
        and bool(value)
        and FILTER_REPLACEMENT_MARKER not in value
        and formation_name_weight(value) <= CLIENT_FORMATION_NAME_WEIGHT_LIMIT
    )


def normalize_stored_formation_name(value: Any, slot: int) -> str:
    """Migrate only missing values and defaults generated by this server."""

    if not isinstance(value, str) or not value:
        return default_formation_name(slot)
    if value in LEGACY_GENERATED_FORMATION_NAMES:
        return default_formation_name(slot)
    return value


__all__ = [
    "CLIENT_FORMATION_NAME_WEIGHT_LIMIT",
    "FILTER_REPLACEMENT_MARKER",
    "LEGACY_GENERATED_FORMATION_NAMES",
    "default_formation_name",
    "formation_name_weight",
    "is_client_valid_formation_name",
    "normalize_stored_formation_name",
]
